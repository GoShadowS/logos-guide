/**
 * app.config.js — динамическая конфигурация Expo.
 *
 * Результат этой функции МЕРДЖИТСЯ с app.json, поэтому важно возвращать ВЕСЬ
 * конфиг (…config) — иначе название, иконка, splash, разрешения и плагины
 * из app.json потеряются.
 *
 * Приложению не нужны ни ключи API, ни сеть: карты, данные и переводы лежат
 * в репозитории. Если появится секрет (например, ключ сервиса обновлений),
 * подставляйте его здесь из process.env — в EAS Build переменные задаются
 * в дашборде expo.dev (Project → Variables).
 */
module.exports = ({ config }) => ({
  ...config,
  extra: {
    ...(config && config.extra ? config.extra : {}),
  },
});
